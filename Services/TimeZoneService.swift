import CoreLocation
import Foundation

enum TimeZoneMatchResult: Equatable, Sendable {
    case matched, withinGracePeriod, unavailable
    case mismatch(deviceZone: String, targetZone: String, hint: String, isEstimated: Bool)
}

enum TimeZoneService: Sendable {
    static func nearestZone(to coordinate: WGS84Coordinate) -> TimeZone? {
        let location = CLLocation(latitude: coordinate.latitude, longitude: coordinate.longitude)
        return zones.lazy.map { (zone: $0.zone, distance: location.distance(from: $0.location)) }
            .min { $0.distance < $1.distance }?.zone
    }

    static func evaluate(record: AppliedLocationRecord, device: TargetDevice, targetTimeZone: TimeZone?,
                         isEstimated: Bool = false, now: Date = Date(), locale: Locale = AppLanguage.locale) -> TimeZoneMatchResult {
        guard now.timeIntervalSince(record.appliedAt) >= 60 else { return .withinGracePeriod }
        guard record.deviceID == device.id, let current = device.timeZoneID.flatMap(TimeZone.init(identifier:)),
              let target = targetTimeZone ?? nearestZone(to: record.coordinate) else { return .unavailable }
        guard current.secondsFromGMT(for: now) != target.secondsFromGMT(for: now) else { return .matched }

        let chinese = locale.language.languageCode == .chinese
        let deviceName = current.localizedName(for: .generic, locale: locale) ?? current.identifier
        let targetName = target.localizedName(for: .generic, locale: locale) ?? target.identifier
        let detail = chinese ? "\(device.kind) 的时区（\(deviceName)）与定位（\(targetName)）不一致。"
            : "Your \(device.kind) uses \(deviceName). The location is in \(targetName). "
        let settings = chinese ? "「设置」>「通用」>「日期与时间」" : "Settings > General > Date & Time"
        let hint: String
        switch device.cellular {
        case .some(false):
            hint = chinese ? "在\(settings)中打开「自动设定时区」。" : "Turn on Set Automatically in \(settings)."
        case .some(true):
            hint = chinese ? "自动时区优先使用运营商网络。在\(settings)中关闭「自动设定时区」，然后手动选择同一时区的城市。"
                : "The carrier network takes priority. Turn off Set Automatically in \(settings) and select a city in the target time zone."
        case nil:
            hint = chinese ? "请在\(settings)中检查设备的时区。" : "Check the device’s time zone in \(settings)."
        }
        return .mismatch(deviceZone: current.identifier, targetZone: target.identifier, hint: detail + hint,
                         isEstimated: isEstimated || targetTimeZone == nil)
    }

